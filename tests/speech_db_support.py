"""Адрес живой базы для доказательных тестов речи — и охрана вокруг него.

Девять наборов тестов чистят за собой `DELETE FROM speech_*`, и это правильно:
доказательство на живой базе стоит дороже мока ровно потому, что видит схему,
типы и планировщик. Но чистка не отличает свои строки от чужих — она удаляет
всё.

Один раз этого хватило. `SPEECH_POSTGRES_TEST_URL` был направлен на ту же базу
`speech`, в которой лежал разобранный корпус из шестидесяти одной реальной
записи: звонки, расшифровки, сегменты. Прогон тестов удалил всё, и заметно это
стало не сразу — экран просто показал пустую выдачу. Записи в MinIO уцелели,
разбор — нет.

Договорённость «запускать тесты только против отдельной базы» этого не
предотвращает: она держится на памяти того, кто выставляет переменную. Поэтому
здесь охрана, а не абзац в README. Имя базы обязано выглядеть тестовым, иначе
набор не собирается вовсе — падение при сборе громче пропуска и случается
раньше первого `DELETE`.
"""

from __future__ import annotations

import os
import re
from typing import Final

#: Имя переменной окружения — одно на все наборы.
ENV_VAR: Final[str] = "SPEECH_POSTGRES_TEST_URL"

#: База считается тестовой, если это видно по имени. Набор намеренно узкий:
#: «похоже на тестовую» должно означать «названа тестовой», а не «кажется
#: неважной». `speech_test`, `speech-test`, `test_speech`, `speech_ci` — да;
#: `speech`, `speech_dev`, `speech_local` — нет: в двух последних живут данные,
#: с которыми работают руками, и потерять их так же обидно.
_TEST_DATABASE_PATTERN: Final[re.Pattern[str]] = re.compile(
    r"(^|[_-])(test|tests|ci)([_-]|$)", re.IGNORECASE
)


class UnsafeTestDatabase(RuntimeError):
    """База под тестами не названа тестовой, а тесты её чистят."""


def _database_name(url: str) -> str:
    """Имя базы из URL. Без разбора DSN целиком: нужен только последний сегмент."""
    path = url.split("?", 1)[0].rsplit("/", 1)[-1]
    return path.strip()


def speech_test_database_url() -> str | None:
    """URL живой базы для тестов речи, либо `None`, если он не задан.

    `None` — законный ответ: на машине без Postgres доказательные наборы
    пропускаются, и это ожидаемо. А вот URL, указывающий на нетестовую базу, —
    не «немного не то»: это чистка чужих данных через несколько секунд. Такой
    случай прерывает сбор набора.
    """
    url = (os.getenv(ENV_VAR) or "").strip()
    if not url:
        return None

    name = _database_name(url)
    if not _TEST_DATABASE_PATTERN.search(name):
        raise UnsafeTestDatabase(
            f"{ENV_VAR} указывает на базу {name!r}, и по имени она не тестовая. "
            "Наборы тестов речи чистят таблицы speech_* целиком — свои строки от "
            "чужих они не отличают. Однажды так был потерян разобранный корпус "
            "реальных записей. Заведи отдельную базу и накати миграции:\n"
            "  createdb speech_test\n"
            "  SPEECH_MS_DATABASE_URL=<...>/speech_test "
            "alembic -c alembic.ini upgrade head\n"
            f"  export {ENV_VAR}=<...>/speech_test"
        )
    return url
