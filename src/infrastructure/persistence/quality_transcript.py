"""На чём стоит оценка: текст и роли расшифровки, и когда она перестаёт действовать.

Действует оценка, поставленная после расшифровки: `evaluated_at` не раньше
`created_at` расшифровки. Переобработка записывает расшифровку заново, с новым
`created_at`, и прежняя оценка устаревает сама.

Роли меняются и без переобработки: их называет модель, и расшифровка при этом
не переписывается. Поэтому тот, кто меняет роли, в той же транзакции удаляет оценки
звонка (`DROP_EVALUATIONS_SQL`): звонок снова ждёт оценки, и следующий запуск
команды ставит её по новым ролям. Мест три: разбор, записавший роли; повторный
разбор, стёрший роли модели (`reprocessing`); команда оценки, назвавшая роли
моно-записи. Роли, которые команда дописывает вместе с оценкой, ложатся в одну
транзакцию с ней, и снимать там нечего.

При чтении реплики не сверяются. Сверка отпечатком стояла в каждом запросе
экрана, и Postgres считал отпечаток по всем звонкам периода, а не только по
оценённым: сводка перечитывала все реплики периода каждым своим запросом.

Отпечаток пишется вместе с оценкой и нужен сверке по требованию —
`python -m src.presentation.cli.evaluate --drop-stale`. Она находит оценки, разошедшиеся с
расшифровкой мимо правил выше: реплики правили прямо в базе. MD5 здесь проверяет
изменение данных, а не подлинность.
"""

from sqlalchemy import text

FINGERPRINT_SQL = """
    (SELECT md5(coalesce(
        jsonb_agg(jsonb_build_array(
            qs.seq, qs.speaker, qs.start_ms, qs.end_ms, qs.text_raw
        ) ORDER BY qs.seq)::text, '[]'
    )) FROM speech_transcript_segments AS qs WHERE qs.call_id = {call_id})
"""

#: Все редакции скрипта разом: роли поменялись у звонка, а не у редакции.
DROP_EVALUATIONS_SQL = text("DELETE FROM speech_call_evaluations WHERE call_id = :call_id")
