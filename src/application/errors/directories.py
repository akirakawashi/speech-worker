"""Нормализованный отказ чтения справочника без зависимости от транспорта NCC."""


class DirectorySourceError(Exception):
    """Причина отказа источника; текст ответа и персональные данные сюда не попадают."""

    def __init__(self, reason: str) -> None:
        """Принять устойчивый код причины для сценария и технического журнала."""
        self.reason = reason
        super().__init__(reason)
