"""Скрипт исходящих продаж «Волны» как чек-лист оценки звонка.

Источник — «Скрипт_Онекта Волна» в редакции от 01.04.2026: лист «Скрипт» с
этапами разговора и лист «РСВ» с ответами на возражения. Контролёры слушают
звонок и ставят по каждому этапу 1 или 0; оценка повторяет ровно эту форму.

Этапы взяты из макета вкладки «Оценка качества», а не нарезаны из скрипта
заново: макет заказчик делал по тому же скрипту, и сводка обязана сходиться с
ним пункт в пункт. Требования к этапам — пересказ скрипта, а не цитата: скрипт
не требует читать текст слово в слово, контролёр засчитывает смысл.

**Неприменимый этап засчитывается.** Правило заказчика записано в макете: «если
возражений не было — этап считается выполненным (1 пункт)». Распространено на
все условные этапы: у оператора, которому клиент не сказал «неудобно
говорить», нет повода эту ситуацию отрабатывать, и ставить ему за неё 0 —
значит наказывать за клиента.

**Версия хранится с каждой оценкой.** Скрипт меняется вместе с тарифами и
акциями. Оценка, поставленная по старой редакции, не должна молча
пересчитываться по новой, иначе вчерашний отчёт перестанет совпадать сам с собой.
"""

from __future__ import annotations

from typing import Final

from pydantic import BaseModel, ConfigDict

from src.domain.calls.contracts import CallSource


class ScriptStage(BaseModel):
    """Этап разговора, за который контролёр ставит 1 или 0."""

    model_config = ConfigDict(frozen=True)

    key: str
    label: str
    #: Что должен сделать оператор — так, как это проверяет контролёр.
    requirement: str
    #: Когда этап вообще применим. Пусто — применим в любом звонке по скрипту.
    applies_when: str = ""
    #: Обязательное условие — в макете помечено «чек-лист». Его пропуск не
    #: слабая продажа, а нарушение, и в сводке такие звонки считаются отдельно.
    mandatory: bool = False


class ScriptObjection(BaseModel):
    """Возражение или вопрос клиента из листа «РСВ» и суть ответа на него."""

    model_config = ConfigDict(frozen=True)

    key: str
    label: str
    expected_answer: str


class CallScript(BaseModel):
    """Версионированный скрипт с этапами, возражениями и исходами."""

    model_config = ConfigDict(frozen=True)

    version: str
    title: str
    #: Звонки какого источника оцениваются по этому скрипту. Отбор на оценку и
    #: сводка идут по источнику, а не по вердикту модели: звонок другого
    #: источника продажей не окажется, и спрашивать о нём модель незачем.
    source: CallSource
    #: Когда звонок вообще оценивается по этому скрипту.
    applies_to: str
    stages: tuple[ScriptStage, ...]
    objections: tuple[ScriptObjection, ...]
    #: Итоги звонка: ключ и подпись.
    outcomes: tuple[tuple[str, str], ...]
    #: Тарифы, которые оператор предлагает на презентации.
    tariffs: str

    def stage(self, key: str) -> ScriptStage | None:
        """Найти этап скрипта по устойчивому ключу."""
        return next((stage for stage in self.stages if stage.key == key), None)

    def objection_label(self, key: str) -> str:
        """Найти подпись возражения по устойчивому ключу скрипта."""
        found = next((item for item in self.objections if item.key == key), None)
        return found.label if found else key

    def outcome_label(self, key: str | None) -> str | None:
        """Найти подпись исхода разговора по ключу скрипта."""
        if key is None:
            return None
        return dict(self.outcomes).get(key, key)


