class JobKind(StrEnum):
    """Этапы конвейера. Порядок здесь — это порядок выполнения."""

    INGEST = "ingest"
    TRANSCRIBE = "transcribe"
    ANALYZE = "analyze"


#: Следующий этап за каждым. Конец цепочки — `None`.
SPEECH_NEXT_JOB_KIND: Final[dict[JobKind, JobKind | None]] = {
    JobKind.INGEST: JobKind.TRANSCRIBE,
    JobKind.TRANSCRIBE: JobKind.ANALYZE,
    JobKind.ANALYZE: None,
}


class JobStatus(StrEnum):
    """Допустимые состояния задания конвейера."""

    QUEUED = "queued"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"
    #: Попытки исчерпаны. Требует решения человека, само не повторится.
    DEAD = "dead"


class JobLane(StrEnum):
    """Полосы обработки.

    Разделение существует ради одного: бэкфилл на два месяца истории не должен
    вытеснять пакет за прошедшие сутки, который обязан быть готов к утру.
    Приоритет задаётся числом в задании, полоса — тем, какие задания воркер
    вообще берёт.
    """

    #: Звонки за прошедшие сутки. Собираются вечером, обрабатываются ночью.
    DAILY = "daily"
    #: История за два месяца. Идёт фоном, уступает суточному пакету.
    BACKFILL = "backfill"


class JobErrorClass(StrEnum):
    """Класс отказа, а не его текст.

    В базу и в интерфейс администратора попадает только класс: тела ответов
    провайдеров, адреса и ключи туда не едут (BR-13). Текст с идентификатором
    запроса остаётся в журнале процесса.
    """

    TIMEOUT = "timeout"
    PROVIDER_ERROR = "provider_error"
    NOT_FOUND = "not_found"
    INVALID_OUTPUT = "invalid_output"
    LEASE_EXPIRED = "lease_expired"
    UNEXPECTED_ERROR = "unexpected_error"


#: Классы, которые не повторяются ни на одном этапе: повтор детерминированного
#: отказа — это занятый воркер и ничего больше.
SPEECH_NON_RETRYABLE_ERRORS: Final[frozenset[JobErrorClass]] = frozenset(
    {JobErrorClass.INVALID_OUTPUT}
)

#: Этапы, для которых `not_found` тоже терминален.
#:
#: Терминальность `not_found` зависит от этапа, а не только от класса отказа.
#: На `ingest` это «записи ещё нет у источника» — сбор идёт вечером, повтор
#: осмыслен, и ADR отводит на него шесть попыток. На `transcribe/analyze`
#: это «исчез объект аудио или транскрипт» — того, что этап читает, больше нет,
#: и никакой повтор его не вернёт; нужна переобработка с более раннего этапа.
SPEECH_NOT_FOUND_TERMINAL_KINDS: Final[frozenset[JobKind]] = frozenset(
    {JobKind.TRANSCRIBE, JobKind.ANALYZE}
)


def is_terminal_error(kind: JobKind, error_class: JobErrorClass) -> bool:
    """Хоронить задание сразу или дать ему ещё попытку.

    Решение принимается здесь, а не в SQL, потому что это политика конвейера, и
    она уже разъезжалась с документом: `backoff_seconds` различала `ingest` и
    `not_found`, а терминальность смотрела на один класс отказа — то есть
    `transcribe` с пропавшим аудио честно ждал и повторялся, пока не кончались
    попытки, вместо того чтобы сразу сказать, что переобрабатывать надо раньше.
    """
    if error_class in SPEECH_NON_RETRYABLE_ERRORS:
        return True
    return error_class is JobErrorClass.NOT_FOUND and kind in SPEECH_NOT_FOUND_TERMINAL_KINDS


