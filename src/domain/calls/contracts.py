    #: Два прохода Whisper по каналам. Вдвое дороже; запасной путь.
    STEREO_TWO_PASS = "stereo_two_pass"
    #: Моно: роли расставляет языковая модель на этапе анализа.
    LLM_ATTRIBUTION = "llm_attribution"
    #: Роли не определялись.
    NONE = "none"


