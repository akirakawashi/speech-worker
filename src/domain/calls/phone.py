"""Номера телефонов: маска для показа и псевдоним для группировки.

Сырой номер клиента в системе не хранится нигде — ни в карточке звонка, ни в
снимке записи источника. Это решение ИБ, а не оптимизация: оно убирает целый
класс утечки, потому что утекать нечему.

Хранится две производные величины, и каждая нужна для своего:

* **маска** — чтобы человек узнал звонок в списке, не увидев номера;
* **хеш с секретной солью** — чтобы найти все звонки одного номера, не зная
  самого номера.

Соль (pepper) лежит в окружении, а не в базе: хеш без неё подбирается за
секунды — пространство российских номеров меньше десяти миллиардов.
"""

from __future__ import annotations

import hashlib
import hmac
import re

#: Всё, что не цифра. Номер приходит в разном виде: `+7 (999) 123-45-67`,
#: `89991234567`, `79991234567`.
_NON_DIGIT = re.compile(r"\D+")

MASK_CHAR = "•"


def normalize_phone(raw: str) -> str | None:
    """Привести номер к цифрам. `None`, если на номер не похоже.

    Российские номера приводятся к виду `7XXXXXXXXXX`: `8` в начале — это тот
    же номер, и без приведения один клиент дал бы два разных псевдонима.
    """
    digits = _NON_DIGIT.sub("", raw or "")
    if not digits:
        return None
    if len(digits) == 11 and digits.startswith("8"):
        digits = "7" + digits[1:]
    if len(digits) < 5 or len(digits) > 15:
        # Короче пяти — это внутренний добавочный, а не номер клиента;
        # длиннее пятнадцати не бывает по E.164.
        return None
    return digits


def mask_phone_number(raw: str) -> str | None:
    """Маска для показа: `+7•••••1234`.

    Последние четыре цифры оставлены намеренно: по ним человек узнаёт звонок,
    который сам же и разбирал, а восстановить номер по ним нельзя.
    """
    digits = normalize_phone(raw)
    if digits is None:
        return None
    # Хвост — четыре цифры, но не больше половины номера. У российского номера
    # это ровно четыре и ничего не меняет; у короткого — не даёт маске выдать
    # весь вход. При хвосте в четыре цифры пятизначный номер печатался как
    # `+1•2345`, то есть «маска» показывала все пять цифр и утверждала
    # обратное.
    tail = digits[-min(4, len(digits) // 2) :]
    hidden = max(1, len(digits) - len(tail) - 1)
    return f"+{digits[0]}{MASK_CHAR * hidden}{tail}"


def hash_phone_number(raw: str, pepper: str) -> str | None:
    """Псевдоним номера: HMAC-SHA256 с секретной солью.

    HMAC, а не просто SHA-256 от склейки: конструкция «соль + значение»
    уязвима к удлинению сообщения, и хотя здесь это не эксплуатируется,
    брать заведомо слабую конструкцию там, где правильная стоит одну строку,
    незачем.

    Пустая соль — отказ, а не хеш без соли: без неё псевдоним подбирается
    перебором всех российских номеров за минуты, то есть перестаёт быть
    псевдонимом.
    """
    if not pepper.strip():
        raise ValueError(
            "phone hashing requires a pepper: an unsalted hash of a phone number "
            "is reversible by enumerating the number space"
        )
    digits = normalize_phone(raw)
    if digits is None:
        return None
    return hmac.new(pepper.encode("utf-8"), digits.encode("utf-8"), hashlib.sha256).hexdigest()


def mask_phones_in_snapshot(snapshot: dict[str, object]) -> dict[str, object]:
    """Заменить в снимке записи источника всё, что похоже на номер, маской.

    Снимок кладётся в базу как есть — он полезен при разборе расхождений с
    источником. «Как есть» не должно означать «вместе с номерами»: маскировать
    надо при записи, а не при чтении, иначе однажды кто-нибудь прочитает мимо
    маскирующего кода.

    Ключи не трогаются: их придумывает источник, номера в них не встречаются.
    """
    return {key: _mask_value(value) for key, value in snapshot.items()}


#: Знаки, которые человек ставит **внутри** написанного номера. Косой черты
#: здесь нет намеренно: `ncc-tm/2026/01/14/...` — это путь, а не номер, и
#: считать `/` разделителем групп значит превратить каждый локатор записи в
#: телефон.
_PHONE_PUNCT = r"[\s()\-.]"

#: Значение целиком — номер. Задано той же группировкой, что и номер в тексте,
#: а не «цифры и знаки»: последнее принимало за номер `2026-01-14`, то есть
#: поле `day` каждого снимка.
_WHOLE_PHONE = re.compile(
    r"^(?:"
    # явный `+` — признак номера сам по себе, страна любая (E.164)
    rf"\+{_PHONE_PUNCT}*\d(?:{_PHONE_PUNCT}*\d){{9,14}}"
    r"|"
    # российская форма: с кодом страны или без, слитно или с разделителями
    rf"(?:[78]{_PHONE_PUNCT}*)?\(?\d{{3}}\)?{_PHONE_PUNCT}*\d{{3}}"
    rf"{_PHONE_PUNCT}*\d{{2}}{_PHONE_PUNCT}*\d{{2}}"
    r")$"
)

#: Номер **внутри** текста. Годится только то, что нельзя спутать с
#: идентификатором: либо код страны, либо разделители между группами.
#:
#: Голая слитная десятка (`1766092829`) сюда не попадает сознательно — именно
#: так выглядит отметка времени внутри `sessionId` NCC, и прежняя редакция
#: превращала её в «телефон» в каждом снимке.
_EMBEDDED_PHONE = re.compile(
    r"(?<![\d+])(?:"
    # с кодом страны: +7 (999) 123-45-67, 8 999 123 45 67, 79991234567
    rf"\+?[78]{_PHONE_PUNCT}*\d{{3}}{_PHONE_PUNCT}*\d{{3}}{_PHONE_PUNCT}*\d{{2}}{_PHONE_PUNCT}*\d{{2}}"
    r"|"
    # без кода страны, но разделители обязательны: (999) 123-45-67
    rf"\(?\d{{3}}\)?{_PHONE_PUNCT}+\d{{3}}{_PHONE_PUNCT}+\d{{2}}{_PHONE_PUNCT}+\d{{2}}"
    r")(?!\d)"
)


def _mask_whole_value(text: str) -> str | None:
    """Замаскировать значение, которое целиком является номером.

    Отдельная ветка от поиска в тексте, потому что у полей источника номер
    приходит значением целиком (`"callerNumber": "+7 (999) 123-45-67"`), и
    требовать от него разделителей или кода страны нельзя: `"9991234567"` в
    поле номера — номер, а не идентификатор.

    Плата за это известна: голая слитная десятка значением целиком — это ещё
    и отметка времени Unix, и такое поле будет замаскировано зря. Размен
    сознательный. Испорченное поле снимка видно и восстановимо из источника,
    утёкший номер клиента — нет.
    """
    stripped = text.strip()
    if not _WHOLE_PHONE.match(stripped):
        return None
    return mask_phone_number(stripped)


def _mask_value(value: object) -> object:
    """Скрыть номер в значении снимка источника согласно правилам хранения номера."""
    if isinstance(value, str):
        whole = _mask_whole_value(value)
        if whole is not None:
            return whole
        return _EMBEDDED_PHONE.sub(lambda m: mask_phone_number(m.group(0)) or m.group(0), value)
    if isinstance(value, dict):
        return {k: _mask_value(v) for k, v in value.items()}
    if isinstance(value, list | tuple):
        return [_mask_value(v) for v in value]
    if isinstance(value, bool):
        # Раньше `int`, потому что в Python `bool` — это `int`, и `True`
        # превратился бы в число 1 для разбора.
        return value
    if isinstance(value, int):
        # Номер, пришедший из JSON числом (`{"caller": 79991234567}`), — это
        # тот же номер. Проверка формы та же, что и для строки, поэтому
        # `duration: 120` числом и остаётся: под номер оно не подходит.
        return _mask_whole_value(str(value)) or value
    return value
